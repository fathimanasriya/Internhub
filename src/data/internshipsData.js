/**
 * Helper function to retrieve an internship by its identifier.
 * Supports string ID ('int-ibm-01'), numeric ID (1 or '1'), or partial matches.
 */
export function getInternshipById(id) {
  if (!id) return sampleInternships[0]

  const cleanId = String(id).trim()

  // 1. Direct match with id
  const directMatch = sampleInternships.find((item) => item.id === cleanId)
  if (directMatch) return directMatch

  // 2. Numeric match (e.g., '1', 1)
  const num = parseInt(cleanId, 10)
  if (!isNaN(num)) {
    const numMatch = sampleInternships.find((item) => item.numericId === num)
    if (numMatch) return numMatch
    if (num >= 1 && num <= sampleInternships.length) {
      return sampleInternships[num - 1]
    }
  }

  // 3. Suffix / Substring match (e.g. 'ibm')
  const partialMatch = sampleInternships.find(
    (item) => item.id.toLowerCase().includes(cleanId.toLowerCase()) || cleanId.toLowerCase().includes(item.id.toLowerCase())
  )
  if (partialMatch) return partialMatch

  // Default fallback
  return sampleInternships[0]
}
